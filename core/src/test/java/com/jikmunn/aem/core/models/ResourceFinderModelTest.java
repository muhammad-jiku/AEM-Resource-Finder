package com.jikmunn.aem.core.models;

import com.day.cq.search.PredicateGroup;
import com.day.cq.search.Query;
import com.day.cq.search.QueryBuilder;
import com.day.cq.search.result.Hit;
import com.day.cq.search.result.SearchResult;
import com.day.cq.wcm.api.Page;
import io.wcm.testing.mock.aem.junit5.AemContext;
import io.wcm.testing.mock.aem.junit5.AemContextExtension;
import org.apache.sling.api.resource.Resource;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.ExtendWith;
import org.mockito.Mock;
import org.mockito.junit.jupiter.MockitoExtension;

import java.util.Arrays;
import java.util.Collections;
import java.util.List;

import static org.junit.jupiter.api.Assertions.*;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.Mockito.when;

/**
 * Query Builder itself needs a real repository session to execute predicates
 * against, which AEM Mocks does not simulate for real queries. The standard
 * pattern (and the honest answer when asked "how do you unit test Query
 * Builder code") is: mock the QueryBuilder/Query/SearchResult/Hit chain with
 * Mockito, seed real content into the mock JCR via AemContext so adaptTo(Page)
 * works on the returned hits, and assert on what the model does with the
 * result — not on whether Query Builder's predicate matching itself works
 * (that's Adobe's code, not ours, to test).
 */
@ExtendWith({AemContextExtension.class, MockitoExtension.class})
class ResourceFinderModelTest {

    private final AemContext context = new AemContext();

    @Mock
    private QueryBuilder queryBuilder;

    @Mock
    private Query query;

    @Mock
    private SearchResult searchResult;

    @Mock
    private Hit hit;

    @BeforeEach
    void setUp() {
        // At test time there's no OSGi bundle manifest (Sling-Model-Packages
        // is generated by the bundle plugin at package time, not compile
        // time), so the model package has to be registered explicitly for
        // adaptTo() to find it.
        context.addModelsForPackage("com.jikmunn.aem.core.models");
        context.registerService(QueryBuilder.class, queryBuilder);

        // Real content in the mock JCR so adaptTo(Page) on the "hit" resource
        // actually resolves to something, instead of null.
        context.create().page(
                "/content/mysite/en/resources/community-fridge",
                "article-page",
                "jcr:title", "Community Fridge Program",
                "jcr:description", "Free food resource, open daily."
        );
    }

    @Test
    void returnsResourcesWhenQuerySucceeds() throws Exception {
        Resource hitResource = context.resourceResolver()
                .getResource("/content/mysite/en/resources/community-fridge");

        when(queryBuilder.createQuery(any(PredicateGroup.class), any())).thenReturn(query);
        when(query.getResult()).thenReturn(searchResult);
        when(searchResult.getHits()).thenReturn(Collections.singletonList(hit));
        when(hit.getResource()).thenReturn(hitResource);

        context.currentResource(context.create().resource(
                "/content/mysite/en/jcr:content/resourcefinder",
                "searchPath", "/content/mysite/en/resources",
                "resultLimit", 10
        ));
        context.request().setResource(context.currentResource());

        ResourceFinderModel model = context.request().adaptTo(ResourceFinderModel.class);

        assertNotNull(model);
        assertFalse(model.isHasError());
        assertFalse(model.isEmpty());
        assertEquals(1, model.getItems().size());
        assertEquals("Community Fridge Program", model.getItems().get(0).getTitle());
    }

    @Test
    void setsErrorFlagWhenSearchPathMissing() {
        context.currentResource(context.create().resource(
                "/content/mysite/en/jcr:content/resourcefinder"
                // no searchPath set
        ));
        context.request().setResource(context.currentResource());

        ResourceFinderModel model = context.request().adaptTo(ResourceFinderModel.class);

        assertNotNull(model);
        assertTrue(model.isHasError());
        assertTrue(model.isEmpty());
    }

    @Test
    void degradesGracefullyWhenQueryBuilderThrows() {
        when(queryBuilder.createQuery(any(PredicateGroup.class), any()))
                .thenThrow(new RuntimeException("simulated repository error"));

        context.currentResource(context.create().resource(
                "/content/mysite/en/jcr:content/resourcefinder",
                "searchPath", "/content/mysite/en/resources"
        ));
        context.request().setResource(context.currentResource());

        ResourceFinderModel model = context.request().adaptTo(ResourceFinderModel.class);

        // The whole point of the try/catch in fetchResources(): a query
        // failure must not throw out of the model and break page render.
        assertNotNull(model);
        assertTrue(model.isHasError());
        assertTrue(model.isEmpty());
    }

    @Test
    void clampsResultLimitToHardCeiling() throws Exception {
        // Regression test for BUGS_FIXED.md #1 — an author-entered limit of
        // 5000 must never reach Query Builder as-is.
        when(queryBuilder.createQuery(any(PredicateGroup.class), any())).thenReturn(query);
        when(query.getResult()).thenReturn(searchResult);
        when(searchResult.getHits()).thenReturn(Collections.emptyList());

        context.currentResource(context.create().resource(
                "/content/mysite/en/jcr:content/resourcefinder",
                "searchPath", "/content/mysite/en/resources",
                "resultLimit", 5000
        ));
        context.request().setResource(context.currentResource());

        context.request().adaptTo(ResourceFinderModel.class);

        org.mockito.ArgumentCaptor<PredicateGroup> captor =
                org.mockito.ArgumentCaptor.forClass(PredicateGroup.class);
        org.mockito.Mockito.verify(queryBuilder).createQuery(captor.capture(), any());

        // Query Builder normalizes the "p.limit" input key to its internal
        // "limit" parameter (com.day.cq.search.Predicate.PARAM_LIMIT) — the
        // PredicateGroup itself doesn't expose it back under "p.limit".
        String appliedLimit = captor.getValue().get(com.day.cq.search.Predicate.PARAM_LIMIT);
        assertEquals("50", appliedLimit, "p.limit must be clamped to the 50-result ceiling");
    }
}
